//! The native host entry: the served program runs on the kernel through the shell's native host.

/// The program file the project carries at its root, written by the shell from the request's served program.
pub const PROGRAM_FILE: &str = "program.json";

/// Generate `src/main.rs`: boot `program.json` with its declared locale catalogs, mount `INIT`, hold until stopped.
pub fn generate_server_main() -> String {
    r#"//! Native host entry point. Generated by the Orbital Rust shell.
//!
//! Runs the served program (`program.json`) on the kernel; each locale it declares is read from `locales/<locale>.json`.

use orbital_shell_rust::host::boot::{boot_embedded, Catalogs};
use orbital_shell_rust::host::run::{hold, mount_init, stop_on_signal};
use std::path::Path;

fn catalogs_of(program: &orbital_core::OrbitalSchema, locales_dir: &Path) -> anyhow::Result<Catalogs> {
    let mut catalogs = Catalogs::new();
    for locale in program.locales.iter().flatten() {
        let file = locales_dir.join(format!("{locale}.json"));
        let raw = std::fs::read_to_string(&file).map_err(|e| {
            anyhow::anyhow!("the program declares locale \"{locale}\" but {} could not be read: {e}", file.display())
        })?;
        let catalog = serde_json::from_str(&raw).map_err(|e| {
            anyhow::anyhow!("catalog {} is not a flat JSON object of strings: {e}", file.display())
        })?;
        catalogs.insert(locale.clone(), catalog);
    }
    Ok(catalogs)
}

fn main() -> anyhow::Result<()> {
    let program_json = std::fs::read_to_string("program.json")
        .map_err(|e| anyhow::anyhow!("read program.json: {e}"))?;
    let program: orbital_core::OrbitalSchema =
        serde_json::from_str(&program_json).map_err(|e| anyhow::anyhow!("parse program.json: {e}"))?;
    let catalogs = catalogs_of(&program, Path::new("locales"))?;
    let runtime = boot_embedded(&program_json, &std::env::vars().collect(), catalogs)?;
    mount_init(&runtime)?;
    let stop = stop_on_signal()?;
    hold(&runtime, &stop);
    Ok(())
}
"#
    .to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_entry_boots_the_served_program_and_carries_no_retired_adapter() {
        let main = generate_server_main();
        assert!(
            main.contains("boot_embedded") && main.contains("mount_init") && main.contains("hold")
        );
        assert!(main.contains(PROGRAM_FILE));
        assert!(!main.contains("compile_error") && !main.contains("axum"));
    }
}
