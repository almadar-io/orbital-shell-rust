//! The native host entry: the served program runs on the kernel through the shell's native host.

/// The program file the project carries at its root, written by the shell from the request's served program.
pub const PROGRAM_FILE: &str = "program.orb";

/// Generate `src/main.rs`: boot `program.orb` (it carries its own messages), mount `INIT`, hold until stopped.
pub fn generate_server_main() -> String {
    r#"//! Native host entry point. Generated by the Orbital Rust shell.
//!
//! Runs the served program (`program.orb`) on the kernel.

#[allow(dead_code)]
mod generated;

use orbital_shell_rust::host::boot::boot_embedded;
use orbital_shell_rust::host::run::{hold, mount_init, stop_on_signal, ProtocolSide};

fn main() -> anyhow::Result<()> {
    let program_json = std::fs::read_to_string("program.orb")
        .map_err(|e| anyhow::anyhow!("read program.orb: {e}"))?;
    let runtime = boot_embedded(&program_json, &std::env::vars().collect())?;
    mount_init(&runtime, ProtocolSide::Server)?;
    let stop = stop_on_signal()?;
    hold(&runtime, &stop);
    Ok(())
}
"#
    .to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_entry_boots_the_served_program_and_carries_no_retired_adapter() {
        let main = generate_server_main();
        assert!(
            main.contains("boot_embedded") && main.contains("mount_init") && main.contains("hold")
        );
        assert!(main.contains(PROGRAM_FILE));
        assert!(!main.contains("compile_error") && !main.contains("axum"));
    }

    #[test]
    fn the_entry_declares_the_generated_models_module() {
        assert!(generate_server_main().contains("#[allow(dead_code)]\nmod generated;"));
    }

    #[test]
    fn the_served_program_is_an_orb_file() {
        assert_eq!(PROGRAM_FILE, "program.orb");
        assert!(generate_server_main().contains("read_to_string(\"program.orb\")"));
        assert!(!generate_server_main().contains("program.json"));
    }
}
