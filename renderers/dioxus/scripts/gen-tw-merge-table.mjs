import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, '../../../../orbital-shell-typescript/renderers/web');
const webLib = path.join(webRoot, 'src/core/lib');
const require = createRequire(path.join(webRoot, 'package.json'));
const pkgDir = path.dirname(path.dirname(require.resolve('tailwind-merge')));
const { getDefaultConfig, mergeConfigs, validators } = await import(pathToFileURL(path.join(pkgDir, 'dist/bundle-mjs.mjs')).href);
const version = JSON.parse(readFileSync(path.join(pkgDir, 'package.json'), 'utf8')).version;

const themeScaleSource = readFileSync(path.join(webLib, 'theme-scale.ts'), 'utf8');
const THEME_SCALE_KEYS = new Function(`${themeScaleSource.replace(/export const/, 'const').replace(/ as const;/, ';')}; return THEME_SCALE_KEYS;`)();
const scale = (keys) => [...keys];

const config = mergeConfigs(getDefaultConfig(), {
  extend: {
    theme: { spacing: scale(THEME_SCALE_KEYS.spacing), borderRadius: scale(THEME_SCALE_KEYS.borderRadius) },
    classGroups: {
      h: [{ h: scale(THEME_SCALE_KEYS.height) }],
      'min-h': [{ 'min-h': scale(THEME_SCALE_KEYS.minHeight) }],
      w: [{ w: scale(THEME_SCALE_KEYS.width) }],
      'font-size': [{ text: scale(THEME_SCALE_KEYS.fontSize) }],
      shadow: [{ shadow: scale(THEME_SCALE_KEYS.boxShadow) }],
    },
  },
});

const names = {
  isAny: 'Any', isArbitraryImage: 'ArbitraryImage', isArbitraryLength: 'ArbitraryLength', isArbitraryNumber: 'ArbitraryNumber',
  isArbitraryPosition: 'ArbitraryPosition', isArbitraryShadow: 'ArbitraryShadow', isArbitrarySize: 'ArbitrarySize',
  isArbitraryValue: 'ArbitraryValue', isInteger: 'Integer', isLength: 'Length', isNumber: 'Number', isPercent: 'Percent', isTshirtSize: 'TshirtSize',
};
const byFn = new Map(Object.entries(names).map(([k, v]) => [validators[k], v]));

const probe = new Proxy({}, { get: (_, key) => [{ __theme: key }] });

const str = (s) => JSON.stringify(s);
function def(d) {
  if (typeof d === 'string') return `Def::S(${str(d)})`;
  if (typeof d === 'function') {
    if (d.isThemeGetter) return `Def::T(${str(d(probe)[0].__theme)})`;
    const n = byFn.get(d);
    if (!n) throw new Error(`unknown validator ${d}`);
    return `Def::V(V::${n})`;
  }
  return `Def::O(&[${Object.entries(d).map(([k, v]) => `(${str(k)}, ${defs(v)})`).join(', ')}])`;
}
const defs = (arr) => `&[${arr.map(def).join(', ')}]`;
const entries = (o) => Object.entries(o).map(([k, v]) => `    (${str(k)}, ${defs(v)}),`).join('\n');
const list = (o) => Object.entries(o).map(([k, v]) => `    (${str(k)}, &[${v.map(str).join(', ')}]),`).join('\n');

const out = `// Generated by scripts/gen-tw-merge-table.mjs from the tailwind-merge ${version} default config
// plus the web renderer's cn.ts extension (theme-scale.ts). Do not edit.
use super::{Def, V};

pub static THEME: &[(&str, &[Def])] = &[
${entries(config.theme)}
];

pub static CLASS_GROUPS: &[(&str, &[Def])] = &[
${entries(config.classGroups)}
];

pub static CONFLICTS: &[(&str, &[&str])] = &[
${list(config.conflictingClassGroups)}
];

pub static CONFLICT_MODIFIERS: &[(&str, &[&str])] = &[
${list(config.conflictingClassGroupModifiers)}
];
`;
writeFileSync(path.join(here, '../src/tw_merge_table.rs'), out);
process.stdout.write(`tailwind-merge ${version}\n`);
